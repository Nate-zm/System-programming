import base64
import os
import json
from typing import List, Dict

def закодировать_файл(файл: str) -> str:
    """
    Читает файл в бинарном режиме и возвращает его содержимое, закодированное в Base64.
    """
    if not os.path.isfile(файл):
        raise FileNotFoundError(f"Файл не найден: {файл}")
    
    with open(файл, 'rb') as f:
        данные = f.read()
    return base64.b64encode(данные).decode('utf-8')


def закодировать_множество_файлов(пути_файлов: List[str]) -> Dict[str, str]:
    """
    Кодирует несколько файлов в Base64.
    
    :param пути_файлов: Список путей к файлам.
    :return: Словарь {имя_файла: base64_строка}.
    """
    результат = {}
    for путь in пути_файлов:
        try:
            имя = os.path.basename(путь)
            результат[имя] = закодировать_файл(путь)
            print(f"Закодирован: {путь}")
        except Exception as e:
            print(f"Ошибка при кодировании {путь}: {e}")
    return результат


