if __name__ == "__main__":
    # Укажите реальные файлы для теста
    тестовые_файлы = [
        "example.txt",      # Текстовый файл
        "image.jpg",        # Бинарный файл (изображение)
        # Добавьте другие файлы по желанию
    ]

    # Фильтруем только существующие файлы
    существующие_файлы = [f for f in тестовые_файлы if os.path.isfile(f)]

    if not существующие_файлы:
        print("Нет подходящих файлов для кодирования. Создайте, например, example.txt.")
        # Создадим пример файла для демонстрации
        with open("example.txt", "w", encoding="utf-8") as f:
            f.write("Это тестовый файл для Base64-кодирования.")
        существующие_файлы = ["example.txt"]

    # Кодируем файлы
    закодированные = закодировать_множество_файлов(существующие_файлы)

    # Выводим результат (первые 100 символов каждого)
    print("\n=== Результаты (первые 100 символов) ===")
    for имя, данные in закодированные.items():
        print(f"{имя}: {данные[:100]}...")

    # Опционально: сохранить в JSON для передачи по сети
    with open("encoded_files.json", "w", encoding="utf-8") as f:
        json.dump(закодированные, f, ensure_ascii=False, indent=2)
    print("\n Результат сохранён в encoded_files.json")